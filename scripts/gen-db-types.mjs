// Generates lib/supabase/database.types.ts from the live PostgREST OpenAPI schema,
// in the same shape as `supabase gen types typescript`, so it needs only the
// service key in .env.local (no Supabase CLI login).
//   node --env-file=.env.local scripts/gen-db-types.mjs
// shortcut: RPC return types aren't in the OpenAPI spec (all typed Json) and FK
// names assume Postgres' default <table>_<column>_fkey (isOneToOne only for PK FKs); switch to
// `supabase gen types` if either ever matters.
import { writeFileSync } from "node:fs";

const url = process.env.NEXT_PUBLIC_SUPABASE_URL;
const key = process.env.SUPABASE_SERVICE_ROLE_KEY;
if (!url || !key) throw new Error("NEXT_PUBLIC_SUPABASE_URL / SUPABASE_SERVICE_ROLE_KEY missing");

const res = await fetch(`${url}/rest/v1/`, {
  headers: { apikey: key, "User-Agent": "node", Accept: "application/openapi+json" },
});
if (!res.ok) throw new Error(`OpenAPI fetch failed: ${res.status} ${await res.text()}`);
const spec = await res.json();

function tsType(p) {
  if (p.enum) return p.enum.map((v) => JSON.stringify(v)).join(" | ");
  switch (p.type) {
    case "string": return "string";
    case "integer":
    case "number": return "number";
    case "boolean": return "boolean";
    case "array": return `${tsType(p.items)}[]`;
    default: return "Json"; // json / jsonb carry no type
  }
}

const q = (s) => (/^[A-Za-z_$][\w$]*$/.test(s) ? s : JSON.stringify(s));
const out = [];
const line = (s) => out.push(s);

line("// Generated by scripts/gen-db-types.mjs from the live schema. Do not edit by hand.");
line("export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];");
line("");
line("export type Database = {");
line("  public: {");
line("    Tables: {");
for (const table of Object.keys(spec.definitions).sort()) {
  const def = spec.definitions[table];
  const required = new Set(def.required ?? []); // PostgREST: required = NOT NULL
  const cols = Object.entries(def.properties);
  const isPk = (p) => (p.description ?? "").includes("<pk/>");
  const row = [], ins = [], upd = [], rels = [];
  for (const [col, p] of cols) {
    const t = tsType(p) + (required.has(col) ? "" : " | null");
    // Insert may omit nullable, defaulted and primary-key (identity/serial) columns.
    // PostgREST hides jsonb defaults (e.g. mock_drafts.seats default '{}'), so jsonb is optional too.
    const optional = !required.has(col) || p.default !== undefined || isPk(p) || p.format === "jsonb";
    row.push(`          ${q(col)}: ${t};`);
    ins.push(`          ${q(col)}${optional ? "?" : ""}: ${t};`);
    upd.push(`          ${q(col)}?: ${t};`);
    const fk = /<fk table='([^']+)' column='([^']+)'\/>/.exec(p.description ?? "");
    if (fk) {
      rels.push(
        `          {\n            foreignKeyName: ${JSON.stringify(`${table}_${col}_fkey`)};\n` +
        `            columns: [${JSON.stringify(col)}];\n            isOneToOne: ${isPk(p)};\n` +
        `            referencedRelation: ${JSON.stringify(fk[1])};\n            referencedColumns: [${JSON.stringify(fk[2])}];\n          },`,
      );
    }
  }
  line(`      ${q(table)}: {`);
  line(`        Row: {\n${row.join("\n")}\n        };`);
  line(`        Insert: {\n${ins.join("\n")}\n        };`);
  line(`        Update: {\n${upd.join("\n")}\n        };`);
  line(`        Relationships: [${rels.length ? `\n${rels.join("\n")}\n        ` : ""}];`);
  line("      };");
}
line("    };");
line("    Views: { [_ in never]: never };");
line("    Functions: {");
for (const path of Object.keys(spec.paths).filter((p) => p.startsWith("/rpc/")).sort()) {
  const schema = spec.paths[path].post?.parameters?.find((x) => x.in === "body")?.schema ?? {};
  const req = new Set(schema.required ?? []);
  const args = Object.entries(schema.properties ?? {}).map(
    ([a, p]) => `${q(a)}${req.has(a) ? "" : "?"}: ${tsType(p)}`,
  );
  line(`      ${q(path.slice(5))}: { Args: ${args.length ? `{ ${args.join("; ")} }` : "Record<PropertyKey, never>"}; Returns: Json };`);
}
line("    };");
line("    Enums: { [_ in never]: never };");
line("    CompositeTypes: { [_ in never]: never };");
line("  };");
line("};");
line("");
line('type PublicTables = Database["public"]["Tables"];');
line('export type Tables<T extends keyof PublicTables> = PublicTables[T]["Row"];');
line('export type TablesInsert<T extends keyof PublicTables> = PublicTables[T]["Insert"];');
line('export type TablesUpdate<T extends keyof PublicTables> = PublicTables[T]["Update"];');

const file = new URL("../lib/supabase/database.types.ts", import.meta.url);
writeFileSync(file, out.join("\n") + "\n");
console.log(`wrote ${Object.keys(spec.definitions).length} tables to ${file.pathname}`);
